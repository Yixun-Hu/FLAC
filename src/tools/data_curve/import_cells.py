#: Where the values under each attestation header come from (codex V finding 1). Every
#: header is ``[<name> (<tag>: <detail>)]``; the file's opening comment repeats this list.
PROVENANCE_TAGS = {
    "configured": "the importer's --arm/--tag and its code constants; read from no artifact",
    "caller-supplied": "the command line; checked only as far as its own lines say",
    "verified": "checked by import_run / validate_cells; [validation contract] lists each",
    "re-read": "read again after validation and written down; nothing compared",
    "recorded": "copied or hashed and written down; compared with nothing",
    "not verified": "what no check of this import establishes",
}


def _header(name, tag, detail):
    """``[<name> (<tag>: <detail>)]`` -- the only header form an attestation has."""
    if tag not in PROVENANCE_TAGS:
        raise ValueError(f"unknown provenance tag {tag!r}")
    return f"[{name} ({tag}: {detail})]"


#: The stamp's header -- also exactly what ``_existing_stamp`` looks for in a rerun.
STAMP_HEADER = _header("import stamp", "recorded",
                       "when and by which code the first import ran; not a check")
#: The ``[import stamp]`` keys, in file order. The only time- or environment-dependent part
#: of an attestation; ``imported_at`` and ``importer_git_sha`` are echoed in every cell.
STAMP_KEYS = ("imported_at", "importer", "importer_git_sha", "importer_tracked_tree",
              "importer_worktree")


def _now_iso():
    """Local time, ISO 8601 to the second with its UTC offset (the worklog's clock)."""
    return datetime.datetime.now().astimezone().isoformat(timespec="seconds")


def _importer_identity():
    """Which code wrote the attestation: the kit worktree's HEAD and its tracked state.

    A record, not a gate -- without git the stamp says ``unavailable`` and the import
    goes on. Untracked files (run logs) are ignored; any modified tracked file flags the
    tree as ``modified``, because then HEAD alone does not name the code that ran.
    """
    def git(*args):
        return subprocess.run(["git", "-C", names.REPO_ROOT, *args], capture_output=True,
                              text=True, timeout=60, check=True).stdout
    try:
        sha = git("rev-parse", "HEAD").strip()
        dirty = git("status", "--porcelain", "--untracked-files=no").strip()
    except (OSError, subprocess.SubprocessError) as err:
        sha = " ".join(f"unavailable ({type(err).__name__}: {err})".split())   # one line
        tree = "unavailable"
    else:
        tree = "clean" if not dirty else "modified (tracked files differ from HEAD)"
    return {"importer": "src.tools.data_curve.import_cells", "importer_git_sha": sha,
            "importer_tracked_tree": tree, "importer_worktree": names.REPO_ROOT}


def _existing_stamp(dest_dir):
    """The ``[import stamp]`` of an attestation already installed at ``dest_dir``, or None.

    An identical rerun renders with THIS stamp instead of a fresh one, so its bytes -- and
    the manifest line that hashes them -- match what the first import installed, and the
    unchanged ``_identical`` comparison still decides. It is never written anywhere: a
    destination that differs in anything else is refused before any write.
    """
    try:
        with open(os.path.join(dest_dir, ATTESTATION_BASENAME)) as fin:
            text = fin.read()
    except OSError:
        return None
    stamp, inside = {}, False
    for line in text.splitlines():
        if line.startswith("["):
            inside = line == STAMP_HEADER
        elif inside and not line.startswith("#"):
            key, sep, value = line.partition(": ")
            if sep and key in STAMP_KEYS:
                stamp[key] = value
    return stamp if set(stamp) == set(STAMP_KEYS) else None


def _cell_lines(e, context, checkout, full):
    """One cell: what C3-C13 verified, the bundle as re-read, and what is only recorded."""
    cell, stamp, reread = f"cell K{e['K']} s{e['seed']}", context["stamp"], e["bundle_reread"]
    lines = ["", _header(cell, "verified", "C3-C13 passed for this cell"),
             f"K: {e['K']}", f"seed: {e['seed']}", f"eval_name: {e['eval_name']}",
             f"checkpoint: {context['ckpt']}", f"checkpoint_sha256: {context['ckpt_sha256']}",
             f"metrics_record: {e['source']}", f"metrics_record_sha256: {e['sha256']}",
             f"imported_copy: {os.path.relpath(e['dest'], checkout)}",
             f"prediction_bundle: {e['bundle']}"]
    lines += [f"{k}: {_value(v)}" for k, v in context["protocol"].items()]
    lines += [f"steps: {names.EVAL_STEPS}", f"cfg_scale: {names.EVAL_CFG_SCALE}",
              f"bundle_artifact_contract: {json.dumps(names.PREDICTIONS_ARTIFACT_CONTRACT)}",
              f"dataset_config: {e['dataset_config']}",
              f"dataset_config_matches_K: yes (C9: meta.dataset_config == "
              f"{e['dataset_config']}, the full unseen-eval config of K={e['K']})",
              f"full_unseen_contract_passed: {full}",
              "item_identity_verified: no (see [limits] N1)",
              "", _header(f"{cell} bundle", "re-read", "prediction_bundle read once after "
                          "validation -- hashed and loaded from the same bytes; nothing "
                          "compared"),
              f"prediction_bundle_sha256: {reread['sha256']}"]
    lines += [f"{key}: {reread[key]}" for key in REREAD_KEYS]
    return lines + ["", _header(f"{cell} recorded", "recorded",
                                "copied or hashed; compared with nothing"),
                    f"dataset_config_sha256: {e['dataset_config_sha256']}",
                    f"record_source_sha (as recorded, unvalidated): {e['record_source_sha']}",
                    f"importer_git_sha: {stamp['importer_git_sha']}",
                    f"imported_at: {stamp['imported_at']}"]


def _render_attestation(context, files, checkout):
    """``ATTESTATION.txt``: ``[<name> (<tag>: <detail>)]`` headers over ``key: value`` lines.

    Every header names where the values under it come from (``PROVENANCE_TAGS``; codex V
    finding 1): configured from the CLI and code constants, supplied by the caller, verified
    by the stated contract, re-read after validation, or only recorded; ``[limits]`` says
    what no check establishes. ``context["stamp"]`` is the one time-dependent part, which
    ``_stage_and_install`` takes from an already-installed attestation when there is one.
    """
    arm, tag, protocol, n_items = (context["arm"], context["tag"], context["protocol"],
                                   context["n_items"])
    full = (f"yes (validate_cells: C7 with names.N_ITEMS_UNSEEN = {n_items} items -- the full "
            "unseen split -- and C9)" if n_items == names.N_ITEMS_UNSEEN else
            f"no (fixture override expect_n={n_items}: C7 checked {n_items} items; the full "
            f"unseen split is {names.N_ITEMS_UNSEEN})")
    lines = [f"# exp_14 data-curve import attestation -- {context['run']}",
             "# Written by src.tools.data_curve.import_cells and installed in the same rename "
             f"as the cells; {MANIFEST_BASENAME} lists its sha256.",
             "# Each [<section> (<tag>: <detail>)] header says where its values come from:"]
    lines += [f"#   {name} -- {meaning}" for name, meaning in PROVENANCE_TAGS.items()]
    lines += ["# Every line is one line, and every value follows its key on it ('key: value'):"
              " a value that str.splitlines() would split refuses the import, so no value adds"
              " a line or a [section]; text in a value that looks like a header or a tag is "
              "still that key's value.",
              "# In a string copied from a record or a bundle (record_source_sha, meta_*), each"
              " non-printable character is written as its Python escape (\\x1b, \\t, "
              "\\u202e) and each backslash as \\\\; paths are written as they are."]
    lines += ["", _header("run", "configured", "--arm/--tag and code constants; no run "
                          "contract, split file, model config or training log is read"),
              f"run_id: {context['run']}", f"arm: {arm}",
              f"backbone: {ARM_BACKBONE_LABEL[arm]}", f"fraction: {names.FRACTIONS[tag]}",
              f"fraction_tag: {tag}",
              f"imported_to: {os.path.relpath(context['dest_dir'], checkout)}",
              "", _header("final checkpoint", "verified", "C1, C2"),
              f"final_checkpoint: {context['ckpt']}",
              f"final_checkpoint_sha256: {context['ckpt_sha256']}",
              "", _header("expected checkpoint digest", "caller-supplied",
                          "--expect-ckpt-sha256"),
              f"expect_ckpt_sha256: {context['expect_ckpt_sha256']}",
              "syntax: verified (64 lowercase hex characters, names._check_ckpt_sha256)",
              "equals_final_checkpoint_bytes: verified (C2)",
              "provenance: not verified (see [limits] N3)",
              "", _header("rows", "configured", "--arm/--tag and code constants"),
              f"label: {_row_label(arm, tag)}", f"protocol: {ARM_PROTOCOL_LABEL[arm]}",
              "protocol_flags: " + " ".join(f"{k}={_value(v)}" for k, v in protocol.items())]
    lines += [f"row_K{K}: {row}" for K, row in zip(context["ks"], context["row_specs"])]
    lines += ["", _header("validation contract", "verified", "the checks import_run and "
                          "validate_cells made; every cell below passed all of them")]
    lines += _contract_lines(protocol, n_items, context["ks"], context["seeds"])
    lines += ["", _header("limits", "not verified", "what no check of this import "
                          "establishes")] + _limit_lines()
    for e in files:
        lines += _cell_lines(e, context, checkout, full)
    lines += ["", STAMP_HEADER, "# Time and importer of the FIRST import; an identical "
              "rerun leaves this file byte-for-byte as it was."]
    lines += [f"{key}: {context['stamp'][key]}" for key in STAMP_KEYS]
    return _join_single_lines(lines, ATTESTATION_BASENAME)


def _write_attestation(staging, checkout, context, files):
    """Write ``ATTESTATION.txt`` into the staging directory; return its sha256."""
    path = os.path.join(staging, names.assert_no_forbidden_substring(ATTESTATION_BASENAME))
    text = _render_attestation(context, files, checkout)       # may refuse; nothing written
    with open(path, "w") as fout:
        fout.write(text)
    return _sha256(path)


def _write_manifest(staging, checkout, run, ckpt, ckpt_sha256, files, attestation):
    """``MANIFEST.sha256``: the sources above, the imported copies below.

    Written INTO the staging directory, so it travels with the files it describes and the
    destination never exists without it. The lower half is a plain ``sha256sum -c`` list
    rooted at the FLAC checkout; the upper half is commented out (``sha256sum`` skips ``#``
    lines) and names the NAS path each copy came from, which is the half a reader needs and
    ``sha256sum`` has no room for. The attestation's line closes the lower half, so
    ``sha256sum -c`` from the checkout root verifies it with the cells. Its one
    time-dependent input is that digest, and an identical rerun re-renders the attestation
    with the installed stamp, so it still produces identical bytes -- which is what makes
    the idempotent path checkable.
    """
    path = os.path.join(staging, MANIFEST_BASENAME)
    lines = [f"# exp_14 data-curve import -- {run}",
             "# written by src.tools.data_curve.import_cells (announcement 04, plan §9 D9)",
             f"# final checkpoint:        {ckpt}",
             f"# final checkpoint sha256: {ckpt_sha256}",
             "#", "# --- sources (sha256  NAS path) ---"]
    lines += [f"#{entry['sha256']}  {entry['source']}" for entry in files]
    lines += ["#", "# --- imported copies (sha256  path relative to the FLAC checkout) ---"]
    lines += [f"{entry['sha256']}  {os.path.relpath(entry['dest'], checkout)}"
              for entry in files]
    digest, dest = attestation
    lines += ["#", "# --- attestation of the cells above (sha256  path relative to the FLAC "
              "checkout) ---", f"{digest}  {os.path.relpath(dest, checkout)}"]
    text = _join_single_lines(lines, MANIFEST_BASENAME)        # may refuse; nothing written
    with open(path, "w") as fout:
        fout.write(text)
    return path


def _stage_and_install(files, dest_dir, checkout, run, ckpt, ckpt_sha256, context):
    """``(violations, "new"|"identical")`` -- build the whole directory, then move it once.

    Installation is all-or-nothing, not just validation (codex D3 finding 3). The complete
    published directory -- ten cells, their attestation AND the manifest -- is assembled in
    a sibling staging directory, every copied byte re-hashed there, and only then moved
    into place with a single ``os.rename``. A failure at any point therefore leaves no
    destination at all, rather than a partial one that the generator's glob would average
    without noticing.

    An existing destination is never merged into: byte-identical means the import already
    happened and this is an idempotent rerun; anything else is a refusal, because a stale
    file from an epoch-renamed earlier run matches the same glob as a fresh one.
    """
    parent = os.path.dirname(dest_dir)
    os.makedirs(parent, exist_ok=True)
    staging = os.path.join(parent, f".incoming-{os.path.basename(dest_dir)}-{os.getpid()}")
    shutil.rmtree(staging, ignore_errors=True)
    try:
        os.makedirs(staging)
        for entry in files:
            basename = names.assert_no_forbidden_substring(os.path.basename(entry["source"]))
            staged = os.path.join(staging, basename)
            shutil.copy2(entry["source"], staged)
            digest = _sha256(staged)
            if digest != entry["sha256"]:
                return [f"{basename}: the copy hashes to {digest}, not the source's "
                        f"{entry['sha256']} -- nothing was imported"], None
            entry["dest"] = os.path.join(dest_dir, basename)
            entry["record_source_sha"] = _recorded_source_sha(staged)
        context = dict(context, stamp=_existing_stamp(dest_dir)
                       or dict(_importer_identity(), imported_at=_now_iso()))
        attestation = (_write_attestation(staging, checkout, context, files),
                       os.path.join(dest_dir, ATTESTATION_BASENAME))
        _write_manifest(staging, checkout, run, ckpt, ckpt_sha256, files, attestation)
        if os.path.exists(dest_dir):
            same, why = _identical(staging, dest_dir)
            if same:
                return [], "identical"
            return [f"{dest_dir} already exists and is not what this import would "
                    f"publish: {why}. Nothing was touched -- remove or move it by hand."], None
        os.rename(staging, dest_dir)
        return [], "new"
    finally:
        shutil.rmtree(staging, ignore_errors=True)


def import_run(nas_root, arm, tag, flac_checkout, expect_ckpt_sha256, seeds=names.SEEDS,
               ks=names.K_VALUES, expect_n=None, ckpt=None):
    """Copy one arm's ten metric JSONs into the FLAC checkout, or copy none of them.

    Returns ``(result, violations)``. ``violations`` non-empty means nothing was copied --
    a half-published arm would be globbed and averaged exactly like a complete one.
    ``ValueError`` is raised for a caller bug (unknown arm/tag, a digest that is not a
    digest): that is not a verdict about the artifacts. An artifact that vanishes or changes
    under the import after it was validated -- a bundle gone before its attestation re-read
    (``OSError``), a bundle whose re-read bytes no longer load (``ValueError``), a record
    whose verified copy no longer parses (``ValueError``) -- also raises, as does a copied
    value or path that would span lines in the attestation or the manifest
    (``ValueError``); in every case nothing has been installed.
    """
    run = names.run_id(arm, tag)                    # validates the arm and the fraction
    # The one rule about what a checkpoint digest may be lives in names; re-stating it here
    # would create a second definition of "valid digest" that can drift from the launcher's.
    names._check_ckpt_sha256(expect_ckpt_sha256)
    run_dir = os.path.join(nas_root, run)
    dest_dir = os.path.join(flac_checkout, IMPORT_SUBDIR, run)
    names.assert_no_forbidden_substring(os.path.join(IMPORT_SUBDIR, run))
    result = {"run_id": run, "arm": arm, "fraction_tag": tag, "run_dir": run_dir,
              "dest_dir": dest_dir, "ckpt": ckpt, "ckpt_sha256": expect_ckpt_sha256,
              "files": [], "manifest": None, "attestation": None, "installed": None,
              "row_specs": [row_spec(arm, tag, K, run) for K in ks]}
    # Discovery is unconditional (codex D3 finding 4). An override used to SKIP it, so an
    # internally consistent step-2500 checkpoint -- its own artifacts, its own digest, the
    # right protocol -- could be published as this arm's @40k result. The flag is now only
    # a cross-check: it must name the file discovery already found.
    discovered, why = _final_checkpoint(run_dir)
    if discovered is None:
        return result, [f"{run}: {why}"]
    if ckpt is not None and os.path.realpath(ckpt) != os.path.realpath(discovered):
        return result, [
            f"{run}: --ckpt-path {ckpt} is not this run's final checkpoint {discovered}; "
            f"only the single step-{names.MAX_STEPS} file may be published"]
    ckpt = result["ckpt"] = discovered
    on_disk, identity, bad = (_hash_and_identify(ckpt) if os.path.exists(ckpt)
                              else (None, None, []))
    if bad:
        return result, [f"{run}: {bad[0]}; nothing was published"]
    if on_disk != expect_ckpt_sha256:
        return result, [f"{run}: {ckpt} hashes to {on_disk}, not the caller-supplied "
                        f"--expect-ckpt-sha256 {expect_ckpt_sha256}"]
    files, violations = validate_cells(ckpt, arm, tag, expect_ckpt_sha256, seeds, ks,
                                       expect_n)
    if violations:
        return result, violations
    # Recorded, never compared (codex T F6/M5) -- and hashed BEFORE the identity re-check
    # below, so the window that check covers includes these reads too.
    _attest_cells(files, arm, tag, ckpt)
    # The one hash above is only worth something if the file is still the one it read.
    try:
        still = _file_identity(ckpt)
    except OSError as err:
        still = ("gone", err)
    if still != identity:
        return result, [f"{run}: {ckpt} changed while this import was reading it "
                        f"({identity} -> {still}); nothing was published"]
    context = {"run": run, "arm": arm, "tag": tag, "ckpt": ckpt, "ckpt_sha256": on_disk,
               "expect_ckpt_sha256": expect_ckpt_sha256, "dest_dir": dest_dir,
               "n_items": names.N_ITEMS_UNSEEN if expect_n is None else expect_n,
               "protocol": _validated_protocol(arm), "ks": tuple(ks), "seeds": tuple(seeds),
               "row_specs": result["row_specs"]}
    try:
        violations, installed = _stage_and_install(files, dest_dir, flac_checkout, run,
                                                   ckpt, expect_ckpt_sha256, context)
    except OSError as err:
        return result, [f"{run}: the install failed and nothing was published "
                        f"({type(err).__name__}: {err})"]
    if violations:
        return result, violations
    result["files"] = files
    result["installed"] = installed
    result["manifest"] = os.path.join(dest_dir, MANIFEST_BASENAME)
    result["attestation"] = os.path.join(dest_dir, ATTESTATION_BASENAME)
    return result, []


def main(argv=None):
    """CLI: import one arm's cells and print the rows to add to gen_model_comparison.py."""
    parser = argparse.ArgumentParser(
        prog="python -m src.tools.data_curve.import_cells",
        description="Copy one exp_14 arm's ten metric JSONs into the FLAC checkout that "
                    "regenerates model_comparison.md, sha-verified, all-or-nothing.")
    parser.add_argument("--nas-root", required=True,
                        help="the directory holding the dc_<arm>_f<tag> run directories")
    parser.add_argument("--arm", required=True, choices=list(names.ARMS))
    parser.add_argument("--tag", required=True, choices=sorted(names.FRACTIONS))
    parser.add_argument("--flac-checkout", required=True,
                        help="the checkout that owns gen_model_comparison.py "
                             "(branch localization-exp)")
    parser.add_argument("--expect-ckpt-sha256", required=True,
                        help="the launch summary's final_ckpt_sha256 for this arm")
    parser.add_argument("--ckpt-path", default=None,
                        help="cross-check: must name the run's discovered step-40000 "
                             "checkpoint, which is published either way")
    args = parser.parse_args(argv)
    try:
        result, violations = import_run(args.nas_root, args.arm, args.tag,
                                        args.flac_checkout, args.expect_ckpt_sha256,
                                        ckpt=args.ckpt_path)
    except (OSError, ValueError) as err:
        print(f"import_cells: {type(err).__name__}: {err}", file=sys.stderr)
        return EXIT_INPUT_ERROR
    if violations:
        print(f"REFUSED: {result['run_id']} was not imported "
              f"({len(violations)} violations); nothing was copied", file=sys.stderr)
        for line in violations:
            print(f"  ! {line}", file=sys.stderr)
        return EXIT_REFUSED
    print(f"imported {len(result['files'])} cells of {result['run_id']} -> "
          f"{result['dest_dir']}")
    print(f"manifest: {result['manifest']} (staged, verified, installed in one move; "
          f"{result['installed']})")
    print(f"attestation: {result['attestation']} (per section: configured, caller-supplied, "
          "verified, re-read or recorded; its sha256 is in the manifest)")
    print("add these rows to worklog/worklog_yixun/gen_model_comparison.py::ROWS, "
          "force-add the JSONs + manifest + attestation, regenerate, commit and push:")
    for row in result["row_specs"]:
        print(f" {row}")
    return EXIT_OK


if __name__ == "__main__":     # pragma: no cover - exercised through main() in tests
    sys.exit(main())
