def seed_glob(seeds=names.SEEDS):
    """``s4[2-6]`` for seeds 42-46 -- derived, with a guard, never typed."""
    low, high = min(seeds), max(seeds)
    if sorted(seeds) != list(range(low, high + 1)) or low // 10 != high // 10:
        raise ValueError(f"seeds {sorted(seeds)} are not one contiguous decade, so a "
                         "single character-class glob cannot name exactly them")
    return f"s{low // 10}[{low % 10}-{high % 10}]"


def _row_label(arm, tag):
    """The rows' first field -- shared by ``row_spec`` and the attestation's header."""
    pct = int(round(names.FRACTIONS[tag] * 100))
    return f"data-curve {arm} f={pct}% @40k (exp_14 data-curve, {ARM_BACKBONE_LABEL[arm]})"


def row_spec(arm, tag, K, run=None, seeds=names.SEEDS):
    """The line to paste into ``gen_model_comparison.py``'s ROWS table for one cell block.

    ``(label, protocol, K, [glob])`` -- the four-field form every row there uses. The glob
    is relative to the FLAC checkout's root, which is what the generator resolves against.
    ``names.run_id`` does the arm/tag validation, so an unknown arm cannot reach the label.

    The label reads ``data-curve <arm> f=<pct>% @40k (exp_14 data-curve, <backbone>)``:
    the experiment and its curve, then the arm's own backbone from ``ARM_BACKBONE_LABEL``
    -- ``CylDINO`` or ``stock DINOv3-S`` -- so neither arm is named after the other. The
    experiment is spelled ``exp_14``; the underscore keeps it clear of ``exp14_``.
    """
    run = run or names.run_id(arm, tag)
    if K not in names.K_VALUES:
        raise ValueError(f"unplanned K={K!r}; the experiment evaluates {names.K_VALUES}")
    label = _row_label(arm, tag)
    pattern = f"{IMPORT_SUBDIR}/{run}/*_K{K}_{seed_glob(seeds)}*.json"
    names.assert_no_forbidden_substring(label)
    names.assert_no_forbidden_substring(pattern)
    return f'("{label}", "{ARM_PROTOCOL_LABEL[arm]}", {K}, ["{pattern}"]),'


def _final_checkpoint(run_dir, step=names.MAX_STEPS):
    """The run's single step-``step`` checkpoint, or ``None`` with a reason."""
    hits = sorted(glob.glob(os.path.join(glob.escape(run_dir), f"*step={step}.ckpt")))
    if len(hits) == 1:
        return hits[0], None
    if not hits:
        return None, f"no step-{step} checkpoint in {run_dir}: this arm is not finished"
    return None, (f"{len(hits)} step-{step} checkpoints in {run_dir} -- which one produced "
                  "the cells beside them is not decidable here")


def _file_identity(path):
    """``(device, inode, size, mtime_ns)`` -- proof the checkpoint is still the one we hashed.

    Cheaper than a second full hash and enough for the two ways a checkpoint stops being
    the bytes we measured: replaced at the same pathname, or rewritten in place.
    """
    info = os.stat(path)
    return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns


def _fd_identity(fileobj):
    """The identity of the OPEN file -- not of whatever the pathname points at now."""
    info = os.fstat(fileobj.fileno())
    return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns


def _digest_of(fileobj):
    """sha256 of an open descriptor, read from its current position in 1 MiB chunks."""
    digest = hashlib.sha256()
    for chunk in iter(lambda: fileobj.read(1 << 20), b""):
        digest.update(chunk)
    return digest.hexdigest()


def _sha256(path):
    """sha256 of a whole file by pathname -- for the cells and their staged copies, whose
    identity is their content and nothing more."""
    with open(path, "rb") as fin:
        return _digest_of(fin)


def _hash_and_identify(path):
    """``(sha256, identity, violations)`` -- a digest and an identity of the SAME bytes.

    Hashing a pathname and then stat-ing it are two questions about two files as soon as
    anything replaces the file in between: ``hash(A) -> stat(B) -> stat(B)`` used to publish
    ten cells with no violation at all (codex D3-fix2 finding 2). So the descriptor is
    opened once, ``fstat``-ed, hashed, and ``fstat``-ed again before it is closed.

    That catches an in-place rewrite. A *replacement* leaves the descriptor on the old
    inode, so ``import_run`` closes that half by comparing this identity against
    ``_file_identity(path)`` once the ten cells have been validated. Still ONE full read.
    """
    with open(path, "rb") as fin:
        identity = _fd_identity(fin)
        digest = _digest_of(fin)
        after = _fd_identity(fin)
    if after != identity:
        return None, None, [f"{path} was rewritten while it was being hashed ({identity} "
                            f"-> {after}), so the digest describes no file that exists"]
    return digest, identity, []


def validate_cells(ckpt, arm, tag, expect_ckpt_sha256, seeds=names.SEEDS,
                   ks=names.K_VALUES, expect_n=None):
    """``(files, violations)`` -- every cell of one arm, gated as a metrics/bundle *pair*.

    ``expect_n`` overrides the 6,337-item contract for fixtures only; production callers
    leave it ``None`` so the split size comes from ``names.N_ITEMS_UNSEEN``.

    **NAS read budget:** the caller hashes the checkpoint once (~0.7 GB) and hands the
    digest in here, so the ten bundles (~260 MB each) are the only other reads -- about
    3.3 GB per arm rather than the ~10 GB it was when every bundle re-hashed the
    checkpoint (codex D3-fix finding 4).
    """
    n_items = names.N_ITEMS_UNSEEN if expect_n is None else expect_n
    cond_method = names.ARM_COND_METHOD[arm]
    files, violations = [], []
    for K in ks:
        for seed in seeds:
            where = f"K{K} s{seed}"
            metrics_path = names.metrics_json_path(ckpt, arm, tag, K, seed)
            bundle_path = names.predictions_pt_path(ckpt, arm, tag, K, seed)
            if not os.path.exists(metrics_path):
                violations.append(f"{where}: no metrics JSON at {metrics_path}")
                continue
            bad = names.check_metrics(metrics_path, ckpt, expect_ckpt_sha256, cond_method,
                                      names.FRAME_AVG_ANGLES, names.ROTATE_DEG,
                                      names.COND_AUTOCAST)
            if not os.path.exists(bundle_path):
                bad.append(f"no prediction bundle at {bundle_path}, so nothing proves this "
                           f"cell covered the full {n_items}-item unseen split")
            else:
                bad += names.check_bundle(bundle_path, n_items, seed, K, arm,
                                          expect_eval_name=names.eval_name(arm, tag, K, seed),
                                          expect_ckpt=ckpt,
                                          expect_ckpt_sha256=expect_ckpt_sha256,
                                          precomputed_ckpt_sha256=expect_ckpt_sha256)
            if bad:
                violations += [f"{where}: {line}" for line in bad]
                continue
            files.append({"source": metrics_path, "K": K, "seed": seed,
                          "sha256": _sha256(metrics_path)})
    return files, violations


def _identical(staging, dest_dir):
    """``(same, why)`` -- is what we would publish byte-for-byte what is already there?"""
    staged, published = sorted(os.listdir(staging)), sorted(os.listdir(dest_dir))
    if staged != published:
        differing = sorted(set(staged) ^ set(published))
        return False, f"its file list differs ({', '.join(differing)})"
    for basename in staged:
        if _sha256(os.path.join(staging, basename)) != \
                _sha256(os.path.join(dest_dir, basename)):
            return False, f"{basename} differs"
    return True, ""


def _validated_protocol(arm):
    """The four conditioning values every cell of ``arm`` was checked against (C5, C10).

    Derived as ``validate_cells`` / ``names.check_metrics`` derive them: the evaluator
    records angles only on the frame-averaged path, so a vanilla cell's are ``None``.
    """
    method = names.ARM_COND_METHOD[arm]
    angles = ([float(a) for a in str(names.FRAME_AVG_ANGLES).split(",")]
              if method == "fa_invariant" else None)
    return {"cond_method": method, "frame_avg_angles": angles,
            "rotate_deg": float(names.ROTATE_DEG), "cond_autocast": names.COND_AUTOCAST}


def _attest_cells(files, arm, tag, ckpt):
    """Add to each validated cell what its attestation states beyond the metrics record.

    Nothing here is a check. The bundle and config paths are the ones ``check_bundle``
    accepted; each bundle is read once more by ``_reread_bundle`` and the config is hashed
    in the importer's worktree -- recorded, never compared (the evaluator stamps no bundle
    digest and names the config by path only). The ten bundle reads (~2.6 GB per arm) are
    the attestation's whole addition to the import's NAS read budget.
    """
    for entry in files:
        K, seed = entry["K"], entry["seed"]
        entry["eval_name"] = names.eval_name(arm, tag, K, seed)
        entry["bundle"] = names.predictions_pt_path(ckpt, arm, tag, K, seed)
        entry["bundle_reread"] = _reread_bundle(entry["bundle"])
        entry["dataset_config"] = names.EVAL_DATASET_CONFIGS[K]
        entry["dataset_config_sha256"] = names.eval_dataset_config_sha256(K)
    return files


#: What a cell's ``bundle`` section states, in file order, after its digest.
REREAD_KEYS = ("meta_n_items", "meta_n_samples", "predictions_shape", "predictions_finite",
               "meta_dataset_config")


def _reread_bundle(path):
    """One validated bundle, read again: its sha256 and the values ``REREAD_KEYS`` name.

    ``check_bundle`` keeps nothing it loads, so what the attestation says about a bundle
    comes from this second read, after validation. The file is read ONCE, hashed, and
    ``torch.load``-ed from those same bytes, so the digest and the values describe one
    content. Nothing is compared -- not with the contract, not with what ``check_bundle``
    loaded ([limits] N5): this exposes what the file says and adds no check. A file that is
    gone raises ``OSError``; bytes that no longer load as a bundle raise ``ValueError`` --
    there is then nothing to state, and nothing is installed.
    """
    import torch  # deferred, as in names.check_bundle: the module imports without torch

    with open(path, "rb") as fin:
        data = fin.read()
    try:
        bundle = torch.load(io.BytesIO(data), map_location="cpu", weights_only=False)
        meta, predictions = bundle["meta"], bundle["predictions"]
        if not isinstance(meta, dict) or not torch.is_tensor(predictions):
            raise TypeError("expected a meta dict and a predictions tensor")
        found = {"meta_n_items": _value(meta.get("n_items")),
                 "meta_n_samples": _value(meta["n_samples"]) if "n_samples" in meta
                 else "absent",
                 "predictions_shape": str(tuple(predictions.shape)),
                 "predictions_finite": "yes" if bool(torch.isfinite(predictions.float()).all())
                 else "no",
                 "meta_dataset_config": _value(meta.get("dataset_config"))}
    except Exception as err:
        raise ValueError(f"{path} no longer loads as a prediction bundle, so its attestation "
                         f"cannot be written ({type(err).__name__}: {err})") from err
    return dict(found, sha256=hashlib.sha256(data).hexdigest())


def _recorded_source_sha(path):
    """The record's own ``source_sha``, or ``"absent"`` (the kit evaluator writes none).

    Read from the STAGED copy, just verified against the validated source's digest, so the
    value comes from the bytes being published. A string goes through ``_printable``; any
    other JSON value's ``str`` is already printable.
    """
    with open(path) as fin:
        record = json.load(fin)
    value = record.get("source_sha") if isinstance(record, dict) else None
    if value is None:
        return "absent"
    return _printable(value) if isinstance(value, str) else str(value)


def _value(v):
    """A value as the attestation writes it: a string via ``_printable``, anything else JSON."""
    return _printable(v) if isinstance(v, str) else json.dumps(v)


def _printable(text):
    """A string copied from an artifact, made readable on its line (codex V-F1 finding 1).

    Each non-printable character (``str.isprintable``: ESC and other controls, format
    characters such as U+202E, non-ASCII spaces) becomes its Python escape, and each
    backslash is doubled so an escape cannot be typed into a value. Line breaks are left
    as they are: ``_join_single_lines`` refuses them -- escaped, a value spanning lines
    would still be published.
    """
    return "".join("\\\\" if ch == "\\" else
                   ch if ch.isprintable() or (ch + ".").splitlines() != [ch + "."] else
                   repr(ch)[1:-1] for ch in text)


def _join_single_lines(lines, what):
    """``lines`` joined, ``\\n``-terminated -- or ``ValueError`` if any is not ONE line.

    The one place either file is joined (codex V-F1 finding 1). A line break is whatever
    ``str.splitlines`` breaks on (``\\n``, ``\\r``, ``\\v``, ``\\f``, ``\\x1c``-``\\x1e``,
    ``\\x85``, U+2028, U+2029), so no reader splits the file anywhere but at the ``\\n``
    written here. The message names the key and the section, is itself one line, and is
    raised before the file is opened; ``_stage_and_install`` then removes its staging
    directory, so nothing is installed.
    """
    section = None
    for line in lines:
        if line and line.splitlines() != [line]:
            key, sep, _ = line.partition(": ")
            name = f"the value of {key!r}" if sep else "a line"
            under = f" under {section}" if section else ""
            raise ValueError(f"{what}: {name}{under} is not one line ({line!r:.200}); a "
                             "copied value may not add lines or sections -- nothing was "
                             "installed")
        if line.startswith("["):
            section = line
    return "\n".join(lines) + "\n"


