"""exp_14: publish one arm's ten cells into the checkout that owns ``model_comparison.md``.

Announcement 04 wants the cross-experiment table updated per arm, immediately -- and the
table is regenerated by globbing raw per-seed metric JSONs *inside* the FLAC checkout on
branch ``localization-exp``. exp_14's cells are written to the NAS instead, so publishing
an arm means copying ten files across and registering a glob for them. Every step of that
fails quietly, which is what this module is for:

* **The glob decides which validator runs.** ``gen_model_comparison.py::is_exp14_row``
  claims any row whose pattern contains ``exp14_`` for the exp_14 *yaw* campaign, with a
  different protocol label and a validator that cannot parse these eval names (finding
  r3-3). Nothing this module emits -- directory, basename, label or pattern -- may carry
  that substring, and ``names.assert_no_forbidden_substring`` is applied to each.
* **A metrics JSON cannot prove it is this cell.** It records no seed and no dataset
  config, so a file left over from an earlier checkpoint, an earlier protocol or a reduced
  eval split reads as a finished result. The import therefore gates on the *pair*: the
  metrics record (checkpoint path, the digest the evaluator stamped in, all four
  conditioning flags) and its sibling prediction bundle (full 6,337-item split, the
  K-appropriate unseen config, same seed, same protocol, exactly-as-scored tensor).
* **A half-published arm is averaged without complaint.** So validation runs over all ten
  cells before a single byte is copied, the copy lands in a staging directory whose files
  are re-hashed before they are moved into place, and every digest is recorded beside the
  source path it came from in ``MANIFEST.sha256``.
* **What the pair proved does not survive the copy (codex T finding F6 / M5).** Only the
  metrics JSONs are installed, and they cannot say which K, seed, split or protocol they
  were scored under. ``ATTESTATION.txt`` -- plain text, so no ``*.json`` row glob matches
  it -- is installed in the same rename. Every section of it says where its values come
  from -- configured, caller-supplied, verified (the contract it states), re-read or
  recorded -- and a ``[limits]`` section says what no check establishes (codex V finding
  1). The manifest lists its digest.
* **A copied value cannot add a line (codex V-F1 finding 1).** A record's ``source_sha``,
  a re-read bundle's meta values and a file name are free text; joined raw, one holding a
  line break became a forged ``(verified: ...)`` section. Both files are joined only by
  ``_join_single_lines``, which refuses -- ``ValueError``, nothing installed -- any line
  that ``str.splitlines`` would split; every value follows its key on its own line.

No GPU, no network, and nothing in the destination checkout is committed or force-added
here: this module copies and prints, the analyst commits.

**Deferred, on purpose (plan §9 D9, codex D3 finding 7).** The plan also requires the
authoritative ``gen_model_comparison.py`` to be RUN end-to-end over a fixture import
directory, asserting five files per K, a numerically rendered row and the final protocol
label. That test belongs to the checkout that owns the generator (branch
``localization-exp``), not here, and the Planner schedules it before the first arm is
published. What this repository can prove -- and does, in
``src/tests/test_data_curve_import_cells.py`` -- is that the emitted string literal-parses
as one of the generator's own four-field ROWS entries and carries no forbidden substring.
"""
