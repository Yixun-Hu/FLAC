def z(m, s, pm, ps): return (m - pm) / math.sqrt(s*s + ps*ps)
def table(rows):
    tr = ""
    for n, m, s, pm, ps in rows:
        zz = z(m, s, pm, ps)
        tr += f'<tr><td>{n}</td><td class="num">{m:.4f} ± {s:.4f}</td><td class="num">{pm} ± {ps}</td><td class="num">{zz:+.2f}σ</td><td><span class="chip pass">✓ PASS</span></td></tr>\n'
    return tr
def dotchart(rows_k1, rows_k8):
    # signed z deviation dot plot, band ±2σ; x linear in z; one row per metric×K
    items = [(f"K=1 {n}", z(m,s,pm,ps)) for n,m,s,pm,ps in rows_k1] + [(f"K=8 {n}", z(m,s,pm,ps)) for n,m,s,pm,ps in rows_k8]
    W, LM, RW, RH = 760, 150, 560, 22
    H = 40 + RH*len(items) + 30
    def X(v): return LM + (v + 2.5) / 5.0 * RW
    s = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="z-deviation of reproduced metrics vs paper">']
    s.append(f'<rect x="{X(-2)}" y="30" width="{X(2)-X(-2)}" height="{RH*len(items)}" fill="var(--div-mid)"/>')
    for gv in (-2,-1,0,1,2):
        s.append(f'<line class="axis" x1="{X(gv)}" y1="30" x2="{X(gv)}" y2="{30+RH*len(items)}"/><text x="{X(gv)}" y="{40+RH*len(items)}" text-anchor="middle">{gv:+d}σ</text>')
    for i,(lab,zz) in enumerate(items):
        cy = 30 + RH*i + RH/2
        s.append(f'<text x="{LM-8}" y="{cy+4}" text-anchor="end">{lab}</text>')
        s.append(f'<circle class="mark" cx="{X(zz)}" cy="{cy}" r="5" fill="var(--s1)"><title>{lab}: {zz:+.2f}σ vs paper</title></circle>')
    s.append(f'<text x="{X(0)}" y="20" text-anchor="middle" class="val">deviation from paper Table 1 (σ of combined std) — gray band = ±2σ</text>')
    s.append('</svg>')
    return "".join(s)
